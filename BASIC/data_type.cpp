#include <iostream>
using namespace std;
 
int main() {

    cout<<sizeof(int)<<endl;                           //4
    cout<<sizeof(long int)<<endl;                     //8
    cout<<sizeof(long long int)<<endl;               //16
    cout<<sizeof(short int)<<endl;                  //2
    cout<<sizeof(signed long int)<<endl;           //4
    cout<<sizeof(unsigned long int)<<endl;        //4 only positive number 
 
return 0;
 
}